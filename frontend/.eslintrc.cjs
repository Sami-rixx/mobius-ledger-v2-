// ESLint configuration for the Mobius Ledger frontend (Vite + React).
//
// NOTE: this file did not previously exist anywhere in the repository (no
// `.eslintrc.*`, no `eslint.config.*`, at the frontend root, repo root, or
// home directory). `npm run lint` / `npm run lint:frontend` (and therefore
// the "gatecheck" quality gate, which chains it in) has never actually
// linted anything - running `eslint . --ext js,jsx` with ESLint 8.57.1 and
// no config file fails immediately with "ESLint couldn't find a
// configuration file" before inspecting a single source file. This is the
// standard configuration generated by Vite's own "react" template and
// matches the eslint/eslint-plugin-react/eslint-plugin-react-hooks/
// eslint-plugin-react-refresh versions already present in package.json.
module.exports = {
  root: true,
  env: { browser: true, es2021: true, node: true },
  extends: [
    'eslint:recommended',
    'plugin:react/recommended',
    'plugin:react/jsx-runtime',
    'plugin:react-hooks/recommended',
  ],
  ignorePatterns: ['dist', '.eslintrc.cjs', 'vite.config.js'],
  parserOptions: { ecmaVersion: 'latest', sourceType: 'module', ecmaFeatures: { jsx: true } },
  settings: { react: { version: 'detect' } },
  plugins: ['react-refresh'],
  rules: {
    'react-refresh/only-export-components': ['warn', { allowConstantExport: true }],
    // react-in-jsx-scope is unnecessary with the modern JSX runtime (already
    // covered by plugin:react/jsx-runtime above), but keep prop-types
    // enforcement on since the codebase already uses PropTypes throughout.
    'react/prop-types': 'warn',
    'no-unused-vars': ['warn', { argsIgnorePattern: '^_', varsIgnorePattern: '^_' }],
  },
};
